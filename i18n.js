export function setLang(l) {
  lang = l === 'en' ? 'en' : 'ar';
  const r = document.documentElement;
  r.lang = lang; r.dir = lang === 'en' ? 'ltr' : 'rtl';
}
export const t = s => (lang === 'en' && EN[s]) || s;

const ATTRS = ['placeholder', 'aria-label', 'alt', 'title'];
/** يترجم نصوص الصفحة الثابتة: يحتفظ بالأصل العربي ليعود إليه عند تبديل اللغة */
export function tr(root = document.body) {
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = w.nextNode())) {
    if (n._ar === undefined) n._ar = n.nodeValue;
    const k = n._ar.trim();
    if (!k) continue;
    const want = lang === 'en' && EN[k] ? n._ar.replace(k, EN[k]) : n._ar;
    if (n.nodeValue !== want) n.nodeValue = want;
  }
  root.querySelectorAll('[placeholder],[aria-label],[alt],[title]').forEach(el => {
    ATTRS.forEach(a => {
      if (!el.hasAttribute(a)) return;
      const key = '_ar_' + a;
      if (el[key] === undefined) el[key] = el.getAttribute(a);
      const k = el[key];
      const want = lang === 'en' && EN[k] ? EN[k] : k;
      if (el.getAttribute(a) !== want) el.setAttribute(a, want);
    });
  });
  document.title = lang === 'en' ? 'Wonasa' : 'ونسة';
}
